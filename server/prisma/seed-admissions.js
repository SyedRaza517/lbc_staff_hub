  for (const a of applicants) {
    const exists = await prisma.admission.findFirst({ where: { email: a.email } });
    if (exists) { skipped++; console.log(`  • skipped (already exists): ${a.firstName} ${a.surname}`); continue; }
    await prisma.admission.create({ data: a });
    created++; console.log(`  ✓ added: ${a.firstName} ${a.surname} — ${a.course}`);
  }
  const total = await prisma.admission.count();
  console.log(`\nDone. Created ${created}, skipped ${skipped}. Admission table now holds ${total} record(s).`);
